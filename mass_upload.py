import os
import sys
import glob
import time
import json
from pathlib import Path
from datetime import datetime, timedelta

# Add the cloned repo to sys.path so we can import it
sys.path.append(os.path.join(os.path.dirname(__file__), "youtube_uploader_selenium"))

# Monkeypatch the broken geckodriver installer with the modern webdriver_manager
from webdriver_manager.firefox import GeckoDriverManager
import selenium_firefox.__utils as sf_utils
sf_utils.Utils.get_geckodriver_path = classmethod(lambda cls, path=None: GeckoDriverManager().install())

from youtube_uploader_selenium import YouTubeUploader

def main():
    if len(sys.argv) < 2:
        print("Usage: python mass_upload.py <folder_path1> [folder_path2] ...")
        sys.exit(1)
        
    folder_paths = sys.argv[1:]
    video_files = []
    for fp in folder_paths:
        video_files.extend(sorted(glob.glob(os.path.join(fp, "*.mp4"))))
    
    # Crucial safeguard: Exclude 2-hour raw source videos from uploading as Shorts!
    video_files = [v for v in video_files if not os.path.basename(v).startswith("source_")]

    if not video_files:
        print(f"No valid shorts .mp4 files found in {', '.join(folder_paths)}")
        sys.exit(1)
        
    print(f"Found {len(video_files)} videos to upload.")
    
    appdata = os.environ.get('APPDATA')
    profiles_dir = os.path.join(appdata, 'Mozilla', 'Firefox', 'Profiles')
    profile_dirs = glob.glob(os.path.join(profiles_dir, '*.default-release*'))
    latest_profile = max(profile_dirs, key=os.path.getmtime) if profile_dirs else None
    
    if latest_profile:
        print(f"Using your actual Firefox profile to bypass login: {latest_profile}")
        profile_path = latest_profile
    else:
        profile_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "youtube_uploader_selenium", "profile"))
        
    # Set up scheduling generator (persist state so multiple runs don't collide)
    schedule_state_file = "schedule_state.json"
    if os.path.exists(schedule_state_file):
        try:
            with open(schedule_state_file, "r") as f:
                state = json.load(f)
                current_schedule_date = datetime.fromisoformat(state["date"])
                current_slot = state["slot"]
        except Exception:
            current_schedule_date = datetime.now() + timedelta(days=1)
            current_slot = 0
    else:
        current_schedule_date = datetime.now() + timedelta(days=1)
        current_slot = 0
        
    for idx, video_path in enumerate(video_files, 1):
        filename = os.path.basename(video_path)
        
        # Extract title from filename (e.g. "01 - Title.mp4" -> "Title")
        title = filename.replace(".mp4", "")
        parts = title.split(" - ", 1)
        if len(parts) == 2 and parts[0].isdigit():
            title = parts[1]
            
        llm_title = title
        meta_path = video_path.replace(".mp4", ".json")
        
        # Extract title from the JSON generated by the LLM
        if os.path.exists(meta_path):
            try:
                with open(meta_path, "r", encoding="utf-8") as f:
                    existing_data = json.load(f)
                    if "title" in existing_data:
                        llm_title = existing_data["title"]
            except Exception:
                pass
                
        final_title = f"{llm_title} #podcast #jre"
        if len(final_title) > 100:
            final_title = final_title[:100]
            
        description = f"{llm_title}\n\nlike and subscribe\n#shorts #podcast #interview #jre #joerogan"
        
        # Determine schedule
        date_str = current_schedule_date.strftime("%m/%d/%Y")
        if current_slot == 0:
            time_str = "22:30"
            current_slot = 1
            # Move to next day for 4:30 AM slot
            current_schedule_date += timedelta(days=1)
        else:
            time_str = "04:30"
            current_slot = 0
            
        schedule_str = f"{date_str}, {time_str}"
        
        metadata = {
            "title": final_title,
            "description": description,
            "tags": ["shorts","usa","joerogan"],
            "schedule": schedule_str
        }
        
        # Save the schedule state for the next execution
        with open(schedule_state_file, "w") as f:
            json.dump({
                "date": current_schedule_date.isoformat(),
                "slot": current_slot
            }, f)
            
        # Save the dedicated metadata JSON file right next to the video
        with open(meta_path, "w", encoding="utf-8") as f:
            json.dump(metadata, f, indent=4)
            
        print(f"\n[{idx}/{len(video_files)}] Uploading: {final_title}")
        
        try:
            # We pass a relative path or absolute path. The library resolves it with Path.cwd()
            uploader = YouTubeUploader(video_path, meta_path, profile_path=profile_path)
            success, video_id = uploader.upload()
            
            if success:
                print(f"[SUCCESS] Successfully uploaded! Video ID: {video_id}")
                # Clean up uploaded files to prevent duplicates and save space
                try:
                    os.remove(video_path)
                    if os.path.exists(meta_path):
                        os.remove(meta_path)
                    print(f"Cleaned up {filename} from output folder.")
                except Exception as e:
                    pass
            else:
                print(f"[ERROR] Failed to upload {filename}. It might be a duplicate.")
        except Exception as e:
            print(f"[ERROR] Exception during upload: {e}")
            
        print("Waiting 15 seconds before the next upload to prevent spam flags...")
        time.sleep(15)
        
    print("Mass upload complete!")

if __name__ == "__main__":
    main()
